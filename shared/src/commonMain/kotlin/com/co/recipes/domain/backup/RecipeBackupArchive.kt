package com.co.recipes.domain.backup

import com.co.recipes.infraestructure.zip.encodeZip
import com.co.recipes.infraestructure.zip.isZip as hasZipHeader
import no.synth.kmpzip.zip.ZipInputStream

/**
 * The `.zip` container the admin backup uses when recipes have photos.
 *
 * Layout:
 * ```
 * recipes-backup-2026-11-11.zip
 * ├── recipes-backup.json          # the same document [RecipeBackupCodec] writes
 * └── images/recipes/<hex>.jpg     # exact storage paths, so a restore re-uploads to
 *     images/steps/<hex>.jpg       # the same object names
 * ```
 *
 * Keeping the JSON as a separate manifest means the backup is still readable and
 * hand-editable (open the zip, edit the JSON), and a collection without images keeps
 * exporting a plain `.json` file exactly as before.
 *
 * Pure Kotlin via kmp-zip: the same bytes are produced on Android, iOS, desktop and the
 * browser, and the round trip is covered by commonTest.
 */
object RecipeBackupArchive {

    const val MANIFEST_ENTRY = "recipes-backup.json"

    private const val IMAGES_FOLDER = "images/"

    /** Guards against a hand-made or hostile archive expanding without bound. */
    private const val MAX_ENTRIES = 250
    private const val MAX_ENTRY_BYTES = 10L * 1024 * 1024
    private const val MAX_TOTAL_BYTES = 100L * 1024 * 1024

    data class Content(
        val manifest: String,
        /** Storage object path -> JPEG bytes, exactly as they must be re-uploaded. */
        val images: Map<String, ByteArray>,
    )

    /** ZIP local file header magic (`PK\x03\x04`). */
    fun isZip(bytes: ByteArray): Boolean = hasZipHeader(bytes)

    fun encode(manifestJson: String, images: Map<String, ByteArray>): ByteArray {
        val entries = buildMap {
            put(MANIFEST_ENTRY, manifestJson.encodeToByteArray())
            // Sorted so two backups of the same collection produce the same archive.
            images.entries.sortedBy { it.key }.forEach { (path, bytes) ->
                put(IMAGES_FOLDER + path, bytes)
            }
        }
        return encodeZip(entries)
    }

    fun decode(bytes: ByteArray): Result<Content> = runCatching {
        var manifest: String? = null
        val images = mutableMapOf<String, ByteArray>()
        var totalBytes = 0L
        var entryCount = 0

        ZipInputStream(bytes).use { zip ->
            while (true) {
                val entry = zip.nextEntry ?: break
                if (entry.isDirectory) {
                    zip.closeEntry()
                    continue
                }

                entryCount++
                require(entryCount <= MAX_ENTRIES) {
                    "That archive contains too many files to be a Shared Recipes backup."
                }
                require(entry.size <= MAX_ENTRY_BYTES) {
                    "“${entry.name}” is too large to be part of a Shared Recipes backup."
                }

                val data = zip.readBytes()
                zip.closeEntry()

                totalBytes += data.size
                require(totalBytes <= MAX_TOTAL_BYTES) {
                    "That archive is too large to be a Shared Recipes backup."
                }

                when {
                    entry.name == MANIFEST_ENTRY -> manifest = data.decodeToString()
                    entry.name.startsWith(IMAGES_FOLDER) -> {
                        val path = entry.name.removePrefix(IMAGES_FOLDER)
                        require(isSafeImagePath(path)) {
                            "That archive contains an unsafe image path (${entry.name})."
                        }
                        images[path] = data
                    }
                    // Anything else is ignored: an OS-made zip often carries .DS_Store,
                    // __MACOSX/… and friends, none of which concern the restore.
                }
            }
        }

        val json = manifest ?: throw IllegalArgumentException(
            "That archive has no $MANIFEST_ENTRY inside. Unzip it and pick the JSON file instead.",
        )

        Content(manifest = json, images = images)
    }

    /** Storage paths are generated by the app; refuse anything that could escape the bucket. */
    private fun isSafeImagePath(path: String): Boolean =
        path.isNotBlank() &&
            path.length <= 300 &&
            !path.startsWith("/") &&
            !path.contains("..") &&
            !path.contains('\\')
}
