-- Migration 10: recipe images.
--
-- Two optional images per recipe, both stored in Supabase Storage and referenced by
-- their object path (never by a full URL, so the project ref stays out of the data):
--
--   * public.recipes.image_path       — the cover photo, shown as the list thumbnail and
--                                       at the top of the recipe;
--   * public.recipe_steps.image_path  — one photo per method step.
--
-- The bucket is public for *read* (Coil fetches thumbnails with a plain URL, like the
-- YouTube stills already did) but every write is admin-only through the storage policies
-- below, which reuse public.is_admin() from migration 2.
--
-- Paths are generated by the app and unique per upload (`recipes/<32 hex>.jpg`,
-- `steps/<32 hex>.jpg`), so replacing an image changes the URL and Coil never serves a
-- stale cached copy. That is why neither column needs a version or a timestamp.

-- ---------------------------------------------------------------------------
-- Columns
-- ---------------------------------------------------------------------------
alter table public.recipes
  add column image_path text check (image_path is null or length(image_path) <= 300);

alter table public.recipe_steps
  add column image_path text check (image_path is null or length(image_path) <= 300);

comment on column public.recipes.image_path is
  'Storage object path in the recipe-images bucket; null = no cover image.';
comment on column public.recipe_steps.image_path is
  'Storage object path in the recipe-images bucket; null = this step has no photo.';

-- ---------------------------------------------------------------------------
-- Storage bucket
--
-- 5 MB and JPEG-only: the app re-encodes every picked photo before uploading, which is
-- also what lets the hand-written PDF embed it with /DCTDecode (no image decoder needed).
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'recipe-images',
  'recipe-images',
  true,
  5242880,
  array['image/jpeg']::text[]
)
on conflict (id) do update
  set public             = excluded.public,
      file_size_limit    = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- Public buckets serve reads through /object/public without consulting RLS, so no SELECT
-- policy is needed for the app to *display* a photo. Listing is different: it queries
-- storage.objects and stays closed here on purpose — the admin maintenance sweep adds its
-- own admin-only SELECT policy in migration 12.
drop policy if exists "recipe images insert admin" on storage.objects;
create policy "recipe images insert admin"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'recipe-images' and public.is_admin());

drop policy if exists "recipe images update admin" on storage.objects;
create policy "recipe images update admin"
  on storage.objects for update to authenticated
  using (bucket_id = 'recipe-images' and public.is_admin())
  with check (bucket_id = 'recipe-images' and public.is_admin());

drop policy if exists "recipe images delete admin" on storage.objects;
create policy "recipe images delete admin"
  on storage.objects for delete to authenticated
  using (bucket_id = 'recipe-images' and public.is_admin());


-- ---------------------------------------------------------------------------
-- Write RPCs now carry the paths.
--
-- The signatures change (a new parameter), and that would otherwise create an *overload* —
-- PostgREST would then have two candidates for the same call. Drop the old signatures
-- first, recreate, and re-grant (grants do not survive a drop).
-- ---------------------------------------------------------------------------
drop function public.create_recipe(text, text, text, int, int, int, jsonb, jsonb);
drop function public.update_recipe(uuid, text, text, text, int, int, int, jsonb, jsonb);

create function public.create_recipe(
  p_title        text,
  p_description  text   default null,
  p_youtube_url  text   default null,
  p_servings     int    default null,
  p_prep_minutes int    default null,
  p_cook_minutes int    default null,
  p_ingredients  jsonb  default '[]'::jsonb,
  p_steps        jsonb  default '[]'::jsonb,
  p_image_path   text   default null
) returns uuid
  language plpgsql
  set search_path = ''
as $$
declare
  v_recipe_id uuid;
begin
  insert into public.recipes (
    title, description, youtube_url, servings, prep_minutes, cook_minutes,
    image_path, created_by
  ) values (
    p_title, p_description, p_youtube_url, p_servings, p_prep_minutes, p_cook_minutes,
    nullif(btrim(coalesce(p_image_path, '')), ''), (select auth.uid())
  )
  returning id into v_recipe_id;

  insert into public.recipe_ingredients (recipe_id, position, quantity, unit, name)
  select
    v_recipe_id,
    coalesce((e ->> 'position')::int, (ord - 1)::int),
    (e ->> 'quantity')::numeric,
    e ->> 'unit',
    e ->> 'name'
  from jsonb_array_elements(coalesce(p_ingredients, '[]'::jsonb)) with ordinality as t(e, ord);

  insert into public.recipe_steps (recipe_id, step_number, instruction, image_path)
  select
    v_recipe_id,
    coalesce((e ->> 'step_number')::int, ord::int),
    e ->> 'instruction',
    nullif(btrim(coalesce(e ->> 'image_path', '')), '')
  from jsonb_array_elements(coalesce(p_steps, '[]'::jsonb)) with ordinality as t(e, ord);

  return v_recipe_id;
end;
$$;


create function public.update_recipe(
  p_recipe_id    uuid,
  p_title        text,
  p_description  text   default null,
  p_youtube_url  text   default null,
  p_servings     int    default null,
  p_prep_minutes int    default null,
  p_cook_minutes int    default null,
  p_ingredients  jsonb  default null,  -- null = leave unchanged
  p_steps        jsonb  default null,  -- null = leave unchanged
  p_image_path   text   default null   -- null = no cover image
) returns void
  language plpgsql
  set search_path = ''
as $$
begin
  update public.recipes set
    title         = p_title,
    description   = p_description,
    youtube_url   = p_youtube_url,
    servings      = p_servings,
    prep_minutes  = p_prep_minutes,
    cook_minutes  = p_cook_minutes,
    image_path    = nullif(btrim(coalesce(p_image_path, '')), '')
  where id = p_recipe_id;

  if p_ingredients is not null then
    delete from public.recipe_ingredients where recipe_id = p_recipe_id;

    insert into public.recipe_ingredients (recipe_id, position, quantity, unit, name)
    select
      p_recipe_id,
      coalesce((e ->> 'position')::int, (ord - 1)::int),
      (e ->> 'quantity')::numeric,
      e ->> 'unit',
      e ->> 'name'
    from jsonb_array_elements(p_ingredients) with ordinality as t(e, ord);
  end if;

  if p_steps is not null then
    -- Steps are replaced wholesale, so each row has to carry its image path back or the
    -- photos would be lost on every edit.
    delete from public.recipe_steps where recipe_id = p_recipe_id;

    insert into public.recipe_steps (recipe_id, step_number, instruction, image_path)
    select
      p_recipe_id,
      coalesce((e ->> 'step_number')::int, ord::int),
      e ->> 'instruction',
      nullif(btrim(coalesce(e ->> 'image_path', '')), '')
    from jsonb_array_elements(p_steps) with ordinality as t(e, ord);
  end if;
end;
$$;

revoke all on function public.create_recipe(text, text, text, int, int, int, jsonb, jsonb, text)
  from public, anon, authenticated;
revoke all on function public.update_recipe(uuid, text, text, text, int, int, int, jsonb, jsonb, text)
  from public, anon, authenticated;

grant execute on function public.create_recipe(text, text, text, int, int, int, jsonb, jsonb, text)
  to authenticated;
grant execute on function public.update_recipe(uuid, text, text, text, int, int, int, jsonb, jsonb, text)
  to authenticated;

-- ---------------------------------------------------------------------------
-- Backup: the paths travel with the JSON so a .zip backup can re-upload the photos to
-- exactly the same object names (see RecipeBackupArchive in the Kotlin client).
-- `create or replace` keeps the existing grants.
-- ---------------------------------------------------------------------------
create or replace function public.admin_export_recipes()
  returns jsonb
  language sql
  stable
  set search_path = ''
as $$
  select coalesce(jsonb_agg(r.recipe order by r.created_at desc), '[]'::jsonb)
  from (
    select
      jsonb_build_object(
        'id',           r.id,
        'title',        r.title,
        'description',  r.description,
        'youtube_url',  r.youtube_url,
        'image_path',   r.image_path,
        'servings',     r.servings,
        'prep_minutes', r.prep_minutes,
        'cook_minutes', r.cook_minutes,
        'created_at',   r.created_at,
        'updated_at',   r.updated_at,
        'deleted_at',   r.deleted_at,
        'created_by',   r.created_by,
        'ingredients', (
          select coalesce(
            jsonb_agg(
              jsonb_build_object(
                'position', i.position,
                'quantity', i.quantity,
                'unit',     i.unit,
                'name',     i.name
              ) order by i.position
            ),
            '[]'::jsonb
          )
          from public.recipe_ingredients i
          where i.recipe_id = r.id
        ),
        'steps', (
          select coalesce(
            jsonb_agg(
              jsonb_build_object(
                'step_number', s.step_number,
                'instruction', s.instruction,
                'image_path',  s.image_path
              ) order by s.step_number
            ),
            '[]'::jsonb
          )
          from public.recipe_steps s
          where s.recipe_id = r.id
        ),
        'comments', (
          select coalesce(
            jsonb_agg(
              jsonb_build_object(
                'id',         c.id,
                'author_id',  c.author_id,
                'body',       c.body,
                'created_at', c.created_at
              ) order by c.created_at
            ),
            '[]'::jsonb
          )
          from public.recipe_comments c
          where c.recipe_id = r.id
        )
      ) as recipe,
      r.created_at
    from public.recipes r
  ) r;
$$;


-- ---------------------------------------------------------------------------
-- Import: same body as migration 9, now writing the two image columns.
-- `create or replace` keeps the existing grants (admin-only).
-- ---------------------------------------------------------------------------
create or replace function public.admin_import_recipes(p_recipes jsonb)
  returns jsonb
  language plpgsql
  security definer
  set search_path = ''
as $$
declare
  v_recipe      jsonb;
  v_id          uuid;
  v_created_by  uuid;
  v_existed     boolean;
  v_was_deleted boolean;
  v_inserted    int := 0;
  v_updated     int := 0;
  v_restored    int := 0;
  v_skipped     int := 0;
begin
  if not public.is_admin() then
    raise exception 'admin_import_recipes is reserved for admins'
      using errcode = '42501';
  end if;

  if jsonb_typeof(coalesce(p_recipes, '[]'::jsonb)) <> 'array' then
    raise exception 'admin_import_recipes expects a jsonb array';
  end if;

  if jsonb_array_length(p_recipes) > 5000 then
    raise exception 'admin_import_recipes accepts at most 5000 recipes per call';
  end if;

  for v_recipe in select * from jsonb_array_elements(p_recipes)
  loop
    begin
      if coalesce(btrim(v_recipe ->> 'title'), '') = '' then
        v_skipped := v_skipped + 1;
        continue;
      end if;

      v_id := case
        when coalesce(v_recipe ->> 'id', '')
             ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
          then (v_recipe ->> 'id')::uuid
      end;

      -- created_by is a FK to auth.users: keep it only when that user still exists
      -- (a backup restored into a different project would otherwise fail).
      v_created_by := case
        when coalesce(v_recipe ->> 'created_by', '')
             ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
          then (
            select u.id from auth.users u where u.id = (v_recipe ->> 'created_by')::uuid
          )
      end;

      v_was_deleted := false;
      v_existed := false;

      if v_id is not null then
        select r.deleted_at is not null
          into v_was_deleted
          from public.recipes r
         where r.id = v_id;
        v_existed := found;
      end if;

      if v_existed then
        update public.recipes set
          title        = btrim(v_recipe ->> 'title'),
          description  = v_recipe ->> 'description',
          youtube_url  = v_recipe ->> 'youtube_url',
          image_path   = nullif(btrim(coalesce(v_recipe ->> 'image_path', '')), ''),
          servings     = (v_recipe ->> 'servings')::int,
          prep_minutes = (v_recipe ->> 'prep_minutes')::int,
          cook_minutes = (v_recipe ->> 'cook_minutes')::int,
          -- A restore means "make this recipe look like the backup", created_at included;
          -- updated_at is left to the trigger.
          created_at   = coalesce((v_recipe ->> 'created_at')::timestamptz, created_at),
          deleted_at   = null
        where id = v_id;
      else
        v_id := coalesce(v_id, gen_random_uuid());

        insert into public.recipes (
          id, title, description, youtube_url, image_path, servings, prep_minutes,
          cook_minutes, created_by, created_at
        ) values (
          v_id,
          btrim(v_recipe ->> 'title'),
          v_recipe ->> 'description',
          v_recipe ->> 'youtube_url',
          nullif(btrim(coalesce(v_recipe ->> 'image_path', '')), ''),
          (v_recipe ->> 'servings')::int,
          (v_recipe ->> 'prep_minutes')::int,
          (v_recipe ->> 'cook_minutes')::int,
          coalesce(v_created_by, (select auth.uid())),
          coalesce((v_recipe ->> 'created_at')::timestamptz, now())
        );
      end if;


      -- Children are replaced wholesale, exactly like update_recipe() does, so a
      -- restored recipe matches the one that was backed up.
      delete from public.recipe_ingredients where recipe_id = v_id;

      insert into public.recipe_ingredients (recipe_id, position, quantity, unit, name)
      select
        v_id,
        coalesce((e ->> 'position')::int, (ord - 1)::int),
        (e ->> 'quantity')::numeric,
        e ->> 'unit',
        e ->> 'name'
      from jsonb_array_elements(coalesce(v_recipe -> 'ingredients', '[]'::jsonb))
        with ordinality as t(e, ord)
      where coalesce(btrim(e ->> 'name'), '') <> '';

      delete from public.recipe_steps where recipe_id = v_id;

      insert into public.recipe_steps (recipe_id, step_number, instruction, image_path)
      select
        v_id,
        coalesce((e ->> 'step_number')::int, ord::int),
        e ->> 'instruction',
        nullif(btrim(coalesce(e ->> 'image_path', '')), '')
      from jsonb_array_elements(coalesce(v_recipe -> 'steps', '[]'::jsonb))
        with ordinality as t(e, ord)
      where coalesce(btrim(e ->> 'instruction'), '') <> '';

      -- Comments are added, never deleted: words written after the backup survive.
      insert into public.recipe_comments (id, recipe_id, author_id, body, created_at)
      select
        (e ->> 'id')::uuid,
        v_id,
        p.id,
        e ->> 'body',
        coalesce((e ->> 'created_at')::timestamptz, now())
      from jsonb_array_elements(coalesce(v_recipe -> 'comments', '[]'::jsonb)) as t(e)
      join public.profiles p on p.id::text = (e ->> 'author_id')
      where coalesce(e ->> 'id', '')
            ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
        and coalesce(btrim(e ->> 'body'), '') <> ''
      on conflict (id) do nothing;

      if v_existed then
        if v_was_deleted then
          v_restored := v_restored + 1;
        else
          v_updated := v_updated + 1;
        end if;
      else
        v_inserted := v_inserted + 1;
      end if;
    exception
      when others then
        -- Malformed row (bad number, over-long text, ...). plpgsql keeps a savepoint
        -- around the begin block, so this row rolls back and the import goes on.
        v_skipped := v_skipped + 1;
    end;
  end loop;

  return jsonb_build_object(
    'inserted', v_inserted,
    'updated',  v_updated,
    'restored', v_restored,
    'skipped',  v_skipped
  );
end;
$$;

